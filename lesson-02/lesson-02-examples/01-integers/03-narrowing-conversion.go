// Розділ 2.1 · Цілі числа
//
// Демонструє: звужувальні перетворення (int64 -> int32) можуть
// спричинити тихе переповнення без паніки і без попередження.
package main

import "fmt"

func main() {
	var big int64 = 3_000_000_000
	var small int32 = int32(big) // тихе переповнення!
	fmt.Println(small)           // -1294967296, без паніки
}
