// Розділ 5.1 · Масиви: фіксований розмір, семантика значень
//
// Демонструє: масив — тип-значення. Присвоєння копіює ВСІ елементи,
// зміна копії не впливає на оригінал.
package main

import "fmt"

func main() {
	var scores [5]int
	scores[0] = 90

	other := scores // ПОВНА КОПІЯ всіх 5 елементів!
	other[0] = 100

	fmt.Println("scores:", scores) // [90 0 0 0 0] — не змінився
	fmt.Println("other: ", other)  // [100 0 0 0 0]
}
