// Розділ 5.4 · copy(), повторне зрізання й підводні камені
//
// Демонструє: класичну підступну помилку — b := a[:2] і a спільно
// використовують базовий масив, тому append(b, ...) непомітно
// псує дані, доступні через a.
package main

import "fmt"

func main() {
	a := []int{1, 2, 3}
	b := a[:2]
	b = append(b, 99) // перезаписує a[2]! спільний базовий масив

	fmt.Println("a:", a) // [1 2 99] — оригінал "непомітно" змінився!
	fmt.Println("b:", b) // [1 2 99]
}
