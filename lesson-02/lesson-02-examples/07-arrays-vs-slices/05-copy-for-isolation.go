// Розділ 5.4 · copy(), повторне зрізання й підводні камені
//
// Демонструє: як гарантувати справжню ізоляцію даних — copy() у
// попередньо виділений зріз, або трюк повного повторного зрізання s[:0:0].
package main

import "fmt"

func main() {
	src := []int{1, 2, 3}

	// Спосіб 1: copy() у попередньо виділений зріз потрібного розміру
	dst := make([]int, len(src))
	n := copy(dst, src)
	dst[0] = 999
	fmt.Println("copy: n =", n, "| dst:", dst, "| src не змінився:", src)

	// Спосіб 2: повне повторне зрізання s[:0:0] змушує наступний
	// append виділити НОВИЙ базовий масив
	isolated := append(src[:0:0], src...)
	isolated[0] = 111
	fmt.Println("isolated:", isolated, "| src не змінився:", src)
}
