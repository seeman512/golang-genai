// Розділ 4.4 · Пастки nil
//
// Демонструє: читання з nil-мапи безпечне, а запис у nil-мапу
// спричиняє паніку. Використано recover(), щоб показати обидва
// випадки в одному запуску.
package main

import "fmt"

func main() {
	var m map[string]int

	// Читання з nil-мапи БЕЗПЕЧНЕ
	fmt.Println("читання з nil-мапи:", m["x"]) // 0, без паніки

	// Запис у nil-мапу спричиняє паніку
	func() {
		defer func() {
			if r := recover(); r != nil {
				fmt.Println("сталася паніка при записі:", r)
			}
		}()
		m["x"] = 1
	}()

	// Правильно: спочатку інціалізувати через make()
	m = make(map[string]int)
	m["x"] = 1
	fmt.Println("після make(): запис успішний, m[\"x\"] =", m["x"])
}
