// Package nilslice демонструє різницю між nil-зрізом і порожнім зрізом —
// саме те, що досліджує Завдання 3 домашньої роботи.
//
// Перш ніж писати код, попросіть ШІ-асистента пояснити різницю між
// var s []int (nil-зріз) та []int{} (порожній зріз), а тоді підсумуйте
// відповідь у README.md своїми словами (3-5 речень).
package nilslice

// NilResult повертає nil-зріз: змінну, яка оголошена, але ніколи
// не отримала значення через make() чи літерал.
//
// а не порожній літерал.
func NilResult() []int {
	var n []int
	return n
}

// EmptyResult повертає порожній, але НЕ nil, зріз — він був явно
// ініціалізований літералом []int{}.
func EmptyResult() []int {
	return []int{}
}

// IsNil — маленький хелпер, що повертає true, якщо переданий зріз
// дійсно nil (а не просто порожній). Реалізовано для вас: це та сама
// перевірка, яку ви будете пояснювати в README.
func IsNil(s []int) bool {
	return s == nil
}
